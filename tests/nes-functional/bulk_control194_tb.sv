`timescale 1ns/1ps
module bulk_control194_tb;
 reg host=0,nes=0,run_host=1;always #5.952 if(run_host)host=~host;always #23.281 nes=~nes;
 reg reset=1,active=1,stop=0,source_fault=0;
 reg valid=0,ending=0;wire ready,end_ready;
 reg [7:0] byte_in=0;reg [4:0] index=0;reg [5:0] length=16;
 reg [1:0] kind=0;reg [9:0] slot=0;reg [15:0] gen=23;
 reg [31:0] seed=32'h19400000;
 reg [23:0] address=0;reg rd=1,wr=1,romsel=1;reg [7:0] din=0;
 wire [7:0] raw,ctl,old;wire ro,co,oo,rdir,cdir,odir;
 wire chunk,ckind,consume,cerror,command_error,fault,sealed;
 wire [11:0] clen;wire [9:0] cslot;wire [15:0] cgen,sgen;
 wire [31:0] token,ctoken;
 integer checks=0,retires=0,errors=0;reg [7:0] gold[0:8191];
 nes_tile_bulk193 producer(.nes_clk(nes),.host_clk(host),.reset(reset),.active(active),.stop(stop),.source_fault(source_fault),
  .tile_valid(valid),.tile_ready(ready),.tile_data(byte_in),.tile_index(index),.tile_length(length),.tile_kind(kind),.tile_slot(slot),.tile_generation(gen),
  .end_valid(ending),.end_ready(end_ready),.end_generation(gen),.token_seed(seed),
  .chunk_ready(chunk),.chunk_length(clen),.chunk_token(token),.chunk_kind(ckind),.chunk_slot(cslot),.chunk_generation(cgen),
  .consume(consume),.consume_token(ctoken),.consume_error(cerror),.address(address),.read_n(rd),.write_n(wr),
  .data_out(raw),.oe_n(ro),.dir(rdir),.fault(fault),.end_sealed(sealed),.sealed_generation(sgen));
 nes_bulk_control194 control(.clk(host),.reset(reset),.active(active),.stop(stop),.fault(fault),
  .chunk_ready(chunk),.chunk_kind(ckind),.chunk_length(clen),.chunk_slot(cslot),.chunk_generation(cgen),.chunk_token(token),
  .address(address),.read_n(rd),.write_n(wr),.data_in(din),.data_out(ctl),.oe_n(co),.dir(cdir),
  .consume(consume),.consume_token(ctoken),.command_error(command_error));
 nes_sink_bus165 #(.PROGRAM_BYTES(8192)) legacy(.clk(host),.reset(reset),.active(active),.stop(stop),.fault(fault),
  .address(address),.read_n(rd),.write_n(wr),.romsel_n(romsel),.data_in(din),.data_out(old),.oe_n(oo),.dir(odir),
  .packet_ready(1'b1),.packet_length(9'd16),.packet_data(8'h5a),.packet_address(),
  .ack_write(),.ack_index(),.ack_byte(),.ack_publish(),.pad_commit(),.pad_buttons());
 always @(posedge host)begin
  if(consume)retires<=retires+1;if(command_error)errors<=errors+1;
  if(cerror)$fatal(1,"control issued wrong token");
 end
 task read_byte(input [23:0] a,input [7:0] expected,input integer owner);
 begin
  @(negedge host);address=a;rd=0;wr=1;romsel=0;repeat(12)@(negedge host);
  if((!ro&&rdir)+(!co&&cdir)+(!oo&&odir)!=1)$fatal(1,"drive overlap/missing %h",a);
  if((owner==0?raw:owner==1?ctl:old)!==expected)$fatal(1,"read %h",a);
  checks=checks+1;rd=1;romsel=1;repeat(4)@(negedge host);
 end endtask
 task write_byte(input [23:0] a,input [7:0] b);
 begin
  @(negedge host);address=a;din=b;rd=1;wr=0;repeat(12)@(negedge host);
  if(co||cdir||!ro||!oo)$fatal(1,"control write routing");
  wr=1;repeat(8)@(negedge host);
 end endtask
 task consume_value(input [31:0] t,input integer bytes);
 integer i;begin for(i=0;i<bytes;i=i+1)write_byte(24'h604c+i,(t>>(8*i))&255);write_byte(24'h6050,8'ha5);end endtask
 task tile(input integer k,input integer s);
 integer i;begin
  @(negedge nes);kind=k;slot=s;length=k==1?32:16;
  for(i=0;i<length;i=i+1)begin
   while(!ready)@(negedge nes);
   valid=1;index=i;byte_in=(s*16+i+k*33)&255;@(negedge nes);valid=0;
  end
 end endtask
 task finish_frame;
 begin @(negedge nes);while(!end_ready)@(negedge nes);ending=1;@(negedge nes);ending=0;repeat(60)@(negedge host);end endtask
 integer i;reg [31:0] t;
 initial begin
  $readmemh("sink-program.hex",gold);repeat(8)@(negedge host);reset=0;repeat(10)@(negedge host);
  // Both the new code extension and mirrored vector bytes use the8KiB ROM.
  read_byte(24'h008000,gold[0],2);read_byte(24'h009050,gold['h1050],2);
  read_byte(24'h00fffc,gold['h1ffc],2);read_byte(24'h00a010,8'hff,2);
  read_byte(24'h400000,8'h5a,2);read_byte(24'h006000,1,2);
  tile(0,0);tile(0,1);tile(1,0);finish_frame();wait(chunk);
  read_byte(24'h6040,1,1);read_byte(24'h6041,0,1);read_byte(24'h6042,32,1);
  read_byte(24'h6043,0,1);read_byte(24'h6044,0,1);read_byte(24'h6045,0,1);read_byte(24'h6046,23,1);read_byte(24'h6047,0,1);
  t=token;for(i=0;i<4;i=i+1)read_byte(24'h6048+i,(t>>(8*i))&255,1);
  consume_value(t,3);if(retires!=0||errors!=1||token!=t)$fatal(1,"partial consume");
  consume_value(t+1,4);if(retires!=0||errors!=2||token!=t)$fatal(1,"wrong consume");
  for(i=0;i<32;i=i+1)read_byte(24'h400800+i,i,0);
  consume_value(t,4);if(retires!=1||token!=t+1||!ckind)$fatal(1,"retire first");
  consume_value(t,4);if(retires!=1||errors!=3)$fatal(1,"stale token");
  read_byte(24'h6041,1,1);for(i=0;i<32;i=i+1)read_byte(24'h400800+i,i+33,0);
  consume_value(token,4);if(retires!=2||chunk)$fatal(1,"retire second");
  // Full2KiB chunk and nonzero slot check are generated by193, not injected.
  for(i=0;i<128;i=i+1)tile(0,i+2);finish_frame();wait(chunk);
  read_byte(24'h6042,0,1);read_byte(24'h6043,8,1);read_byte(24'h6044,32,1);
  for(i=0;i<2048;i=i+1)read_byte(24'h400800+i,(i+32)&255,0);
  // Abort even while host clock is stopped; no stale token bytes survive.
  write_byte(24'h604c,token[7:0]);@(negedge host);run_host=0;address=24'h6040;rd=0;#50;stop=1;#10;
  if(!co||!ro)$fatal(1,"stopped clock cancellation");
  rd=1;seed=32'h19410000;#50;run_host=1;repeat(5)@(negedge host);stop=0;repeat(10)@(negedge host);
  tile(0,0);finish_frame();wait(chunk);
  consume_value(token,3);if(retires!=2||errors!=4)$fatal(1,"partial survived reset");
  consume_value(token,4);if(retires!=3||chunk||fault)$fatal(1,"fresh restart");
  $display("PASS CONTROL194 checks=%0d retires=%0d rejected=%0d",checks,retires,errors);$finish;
 end
 initial begin #20000000;$fatal(1,"watchdog");end
endmodule
