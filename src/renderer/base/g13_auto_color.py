"""C2 bounded per-frame probe of channel0's final written color.
This is ONE color/frame, not a full palette monitor. Prior first failure is
kept for later manual X; no FPGA fault is masked and no automatic halt occurs.
1b20 samples16,22 mismatches16,24 slot,25 status(A1/E1),26got16,28want16.
Length of channel0 is cached at each metadata buffer+80 during its DMA copy.
"""
def emit_auto(a):
    a.label('c2_auto')
    a.read(0x3f);a.branch(0xd0,'c2_started');a.emit(0x60)
    a.label('c2_started');a.read(0x2d);a.emit(0xc9,0x7f);a.branch(0xf0,'c2_enabled');a.emit(0x60)
    a.label('c2_enabled');a.emit(0x5a) # PHY, caller IRQ already preserved full A/X
    a.read(0x12);a.emit(0x49,1,0x0a,0x0a,0x0a,0x0a,0x0a,0x09,0x40);a.sta(0x91)
    a.write(0x90,0x80);a.write(0x92,0x7e);a.emit(0xa0,0,0,0xc2,0x20,0xb7,0x90)
    a.emit(0xc9,6,0);a.branch(0xb0,'c2_length_min');a.jump('c2_bad16');a.label('c2_length_min')
    a.emit(0xc9,0xd7,2);a.branch(0x90,'c2_length_max');a.jump('c2_bad16');a.label('c2_length_max')
    a.emit(0x38,0xe9,6,0,0xa8,0xe2,0x20) # Y points at final record
    a.stz(0x90);a.emit(0xe6,0x91,0xc8,0xb7,0x90,0xc9,64);a.emit(0x90,3);a.jump('c2_bad8');a.sta(0x9a)
    a.emit(0xc8,0xb7,0x90,0xc5,0x9a);a.emit(0xf0,3);a.jump('c2_bad8')
    a.emit(0xc8,0xb7,0x90);a.sta(0x9c)
    a.emit(0xc8,0xb7,0x90);a.emit(0x10,3);a.jump('c2_bad8');a.sta(0x9d)
    a.emit(0xc8,0xb7,0x90);a.emit(0xf0,3);a.jump('c2_bad8')
    a.read(0x9a);a.sta(0x2121)
    a.read(0x213b);a.sta(0x9e);a.read(0x213b);a.emit(0x29,0x7f);a.sta(0x9f)
    a.emit(0xc2,0x20);a.read(0x1b20);a.emit(0xc9,0xff,0xff);a.branch(0xf0,'c2_sample_full');a.emit(0xee,0x20,0x1b)
    a.label('c2_sample_full');a.read(0x9e);a.emit(0xc5,0x9c);a.branch(0xf0,'c2_done16')
    a.read(0x1b22);a.branch(0xd0,'c2_seen')
    a.read(0x9e);a.sta(0x1b26);a.read(0x9c);a.sta(0x1b28);a.emit(0xe2,0x20)
    a.read(0x9a);a.sta(0x1b24);a.emit(0xc2,0x20)
    a.label('c2_seen');a.read(0x1b22);a.emit(0xc9,0xff,0xff);a.branch(0xf0,'c2_done16');a.emit(0xee,0x22,0x1b)
    a.label('c2_done16');a.emit(0xe2,0x20);a.write(0x1b25,0xa1)
    a.read(0x1b22);a.branch(0xd0,'c3_freeze');a.emit(0x7a,0x60)
    a.label('c3_freeze')
    # First failure only: repeat the same CGADD/read pair twice before stop.
    for dest in (0x1b30,0x1b32):
        a.read(0x1b24);a.sta(0x2121)
        a.read(0x213b);a.sta(dest);a.read(0x213b);a.emit(0x29,0x7f);a.sta(dest+1)
    a.stz(0x420c);a.stz(0x4200)
    a.read(0x12);a.emit(0x49,1);a.sta(0x1b36)
    a.write(0x24,5);a.emit(0x7a);a.jump('g10_show')
    a.label('c2_bad16');a.emit(0xe2,0x20)
    a.label('c2_bad8');a.write(0x1b25,0xe1);a.emit(0x7a,0x60)

