    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--out',type=Path,required=True)
    a=p.parse_args();install();r=prior.build(a.out.resolve())
    r.update(candidate='maskboundary247_diagnostic',sink_version='2471',seal_version='2471',seal_bytes=190,
             metadata_end=0x1600,bitmap_bytes=754,map_control_bytes=6,map_initialization_bytes=2,
             state_extra_allocated_bytes=166,receipt_address='7E1500..15ff',valid_addresses=['7E1340..13e5','7E13e6..148b'],
             initialization_address='7E148c..148d',order_address='7E148e..148f',manifest_cursor_address='7E1490..1491',
             manifest_sizes=[240,16],map_opcode=9,manifest_opcode=10,scope=__doc__,
             script_sha256=sha(Path(__file__)),implementation_selected=False,runtime_verified=False,
             emulator_executed=False,size_gate_passed=r['body_bytes']<=3936,
             decision='SIZE_PASS_RUNTIME_PENDING' if r['body_bytes']<=3936 else 'REJECT_ROM_CAPACITY_BEFORE_REPLAY')
    (a.out/'result.json').write_text(json.dumps(r,indent=2)+'\n',encoding='utf-8')
