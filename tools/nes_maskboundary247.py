BASE_SOURCE = prior.source


def source(s):
    s = BASE_SOURCE(s).replace('0x11,0x23', '0x71,0x24')
    s = once(s, '(0x1220,0x150a)', '(0x1220,0x15fe)')
    s = once(s, 'imm(198)', 'imm(166)')
    s = once(s, 'c.emit(0xa2,196,0);', 'c.emit(0xa2,164,0);')
    s = once(s, "c.branch(0x10,'dirty_clear212');c.jump('accepted')", """c.branch(0x10,'dirty_clear212')
 c.absolute(0x9c,0x148e);c.absolute(0x9c,0x1490)
 c.emit(0xa2,254,0);c.label('map_clear247');c.absolute(0x9e,0x1500);c.emit(0xca,0xca);c.branch(0x10,'map_clear247');c.jump('accepted')""")
    s = once(s, " c.emit(0xc9,3,0);cond(0xf0,'seal')", """ c.emit(0xc9,3,0);cond(0xf0,'seal')
 c.emit(0xc9,9,0);cond(0xf0,'map_packet247');c.emit(0xc9,10,0);cond(0xf0,'manifest_packet247')""")
    s = once(s, " c.label('begin');", """ c.label('map_packet247');checkimm(0x1200,0x0209);checkimm(0x120a,0)
 call(c,'mask247');c.jump('map_result247')
 c.label('manifest_packet247');checkimm(0x1200,0x020a);call(c,'manifest247')
 c.label('map_result247');cond(0x90,'bad_packet');call(c,'service');lda(0x1236);cond(0xd0,'stop_packet');c.jump('accepted')
 c.label('begin');""")
    # Only the dedicated word path can write map data. All old DATA/RLE
    # dispatches still reach this check; COPY remains rejected upstream.
    s = once(s, "cond(0xb0,'bad_packet');c.emit(0x0a,0xaa)\n c.emit(0xe0,8,0)",
             "cond(0xb0,'bad_packet');c.emit(0xc9,2,0);cond(0xf0,'bad_packet');c.emit(0x0a,0xaa)\n c.emit(0xe0,8,0)")
    s = once(s, 'checkimm(0x120c,222)', 'checkimm(0x120c,190)')
    # Only after upload has returned success and ordinary display retirement.
    s = once(s, ' lda(0x1240);sta(0x1242)\n c.absolute(0x9c,0x1228)', """ lda(0x1240);sta(0x1242)
 c.absolute(0xae,0x1034);c.emit(0xe2,0x20,0xa9,1);c.absolute(0x9d,0x148c);c.emit(0xc2,0x20)
 c.absolute(0x9c,0x1228)""")
    # STOP is terminal until reset; revoke both initialization bytes at latch.
    s = once(s, ' c.store(0x1236,1)', ' c.store(0x1236,1);c.absolute(0x9c,0x148c);c.absolute(0x9c,0x148d)')
    return s


def transform_emit(s):
    # Remove old map validity holes.166B each: patterns144,CGRAM4,raw18.
    for a,b in [('0x1380','0x1340'),('0x1434','0x13d4'),('0x14fa','0x147a'),
                ('0x1310','0x1310'),('0x1410','0x13d0')]:
        s=s.replace(a,b)
    s=once(s,"lda(0x60);c.emit(0xc9,4,0);cond(0x90,'append_new212');lda(0x7c);","lda(0x7c);")
    s=once(s,"c.label('mark212')", "c.label('mark212');c.emit(0xe0,4,0);cond(0xf0,'mark_bad212')")
    s=once(s,"imm(1408);c.emit(0xe0,6,0)","imm(1152);c.emit(0xe0,6,0)")
    s=once(s,'imm(1440)','imm(1184)')
    s=once(s,'c.emit(0x18,0x69,36,0)','c.emit(0x18,0x69,4,0)')
    s=once(s," c.label('coverage212');c.emit(0xa2,0,0)", """ c.label('coverage212');lda(0x1490);c.emit(0xc9,0,1);cond(0xd0,'mark_bad212')
 c.absolute(0xae,0x1034);c.absolute(0xbd,0x148c);c.emit(0x29,255,0);cond(0xd0,'map_initialized247')
 c.emit(0xa2,254,0);c.label('map_cold247');c.absolute(0xbd,0x1500);c.emit(0xc9,255,255);cond(0xd0,'mark_bad212');c.emit(0xca,0xca);c.branch(0x10,'map_cold247')
 c.label('map_initialized247');c.emit(0xa2,0,0)""")
    # New routines emitted before immutable lookup tables; label fixups stay
    # generated by the same assembler, never patched in a binary afterward.
    s=once(s,' for values,fix in [', ' emit_boundary(c)\n for values,fix in [')
    return s


def emit_boundary(c):
    def lda(a):c.absolute(0xad,a)
    def sta(a):c.absolute(0x8d,a)
    def imm(v):c.emit(0xa9);c.word(v)
    def cond(op,label):c.emit(op^0x20,3);c.jump(label)
    def call(label):prior.call(c,label)
    # DP80=payload cursor,82=end,84=remaining mask,86=map byte offset.
    # append212 owns60..7c; service preserves widths and this scratch.
    c.label('mask247');lda(0x1490);cond(0xd0,'mark_bad212')
    lda(0x120c);c.emit(0xc9,5,0);cond(0x90,'mark_bad212');sta(0x82)
    c.long(0xaf,0x400010);c.emit(0x29,255,0,0xc9,2,0);cond(0xd0,'mark_bad212')
    imm(1);sta(0x80)
    c.label('mask_record247');lda(0x80);c.emit(0x18,0x69,2,0);c.absolute(0xcd,0x82);cond(0xb0,'mark_bad212')
    c.absolute(0xae,0x80);c.long(0xbf,0x400010);c.emit(0x29,255,0)
    c.absolute(0xcd,0x148e);cond(0x90,'mark_bad212');c.emit(0xaa,0x1a);sta(0x148e)
    c.emit(0x8a,0x0a,0x0a,0x0a,0x0a);sta(0x86)
    c.emit(0xda);c.absolute(0xae,0x80);c.long(0xbf,0x400010);c.emit(0xeb,0x29,255,0,0xfa,0xc9,0,0);cond(0xf0,'mark_bad212');sta(0x84)
    # Strict global group ordering proves this receipt byte was never set.
    c.emit(0xe2,0x20);c.absolute(0x9d,0x1500);c.emit(0xc2,0x20)
    lda(0x80);c.emit(0x18,0x69,2,0);sta(0x80)
    c.label('mask_word247');c.absolute(0x4e,0x84);cond(0x90,'mask_skip247')
    lda(0x80);c.emit(0x18,0x69,2,0);c.absolute(0xcd,0x82);cond(0x90,'mask_value247');cond(0xd0,'mark_bad212')
    c.label('mask_value247');c.absolute(0xae,0x80);c.long(0xbf,0x400010);sta(0x88)
    lda(0x86);c.emit(0x18);c.absolute(0x6d,0x1020);c.emit(0xaa);lda(0x88);c.long(0x9f,0x7f5000)
    lda(0x80);c.emit(0x18,0x69,2,0);sta(0x80)
    lda(0x86);c.emit(0x18);c.absolute(0x6d,0x1020);c.emit(0x69,0,0x50);sta(0x70)
    lda(0x1034);c.emit(0xeb,0x0a,0x0a,0x0a,0x0a,0x0a,0x0a,0x18,0x69,0,0x60);c.absolute(0x6d,0x86);sta(0x72)
    imm(2);sta(0x74);imm(4);sta(0x60);call('append212');cond(0x90,'mark_bad212')
    c.label('mask_skip247');lda(0x86);c.emit(0x1a,0x1a);sta(0x86);lda(0x84);cond(0xd0,'mask_word247')
    call('service');lda(0x1236);cond(0xd0,'mark_ok212')
    lda(0x80);c.absolute(0xcd,0x82);cond(0x90,'mask_record247');c.jump('mark_ok212')
    # No extra expected256B array. Exact packet offsets0/240 and sizes240/16
    # prevent duplicates, omissions, overlap and early SEAL. All words match.
    c.label('manifest247');lda(0x120a);c.absolute(0xcd,0x1490);cond(0xd0,'mark_bad212')
    lda(0x1490);cond(0xf0,'manifest_first247')
    c.emit(0xc9,240,0);cond(0xd0,'mark_bad212');imm(16);c.jump('manifest_size247')
    c.label('manifest_first247');imm(240)
    c.label('manifest_size247');c.absolute(0xcd,0x120c);cond(0xd0,'mark_bad212');c.emit(0xa2,0,0)
    c.label('manifest_loop247');c.emit(0x8a,0x18);c.absolute(0x6d,0x1490);c.emit(0xa8)
    c.long(0xbf,0x400010);c.absolute(0xd9,0x1500);cond(0xd0,'mark_bad212')
    c.emit(0xe8,0xe8);c.absolute(0xec,0x120c);c.branch(0xd0,'manifest_loop247')
    lda(0x1490);c.emit(0x18);c.absolute(0x6d,0x120c);sta(0x1490);c.jump('mark_ok212')


def install():
    prior.source=source
    s=inspect.getsource(prior.emit)
    s=once(s,"ns=dict(old.__dict__);exec(compile(s,'sparse232-emit','exec'),ns)",
           "s=transform_emit(s);ns=dict(old.__dict__);ns['emit_boundary']=emit_boundary;exec(compile(s,'sparse232-emit','exec'),ns)")
    ns=dict(prior.__dict__);ns.update(transform_emit=transform_emit,emit_boundary=emit_boundary)
    exec(compile(s,'maskboundary247-emit','exec'),ns);prior.emit=ns['emit']
    s=inspect.getsource(prior.emit_upload).replace('0x1330','0x1310').replace('0x1332','0x1312')
    ns=dict(prior.__dict__);exec(compile(s,'maskboundary247-upload','exec'),ns);prior.emit_upload=ns['emit_upload']


