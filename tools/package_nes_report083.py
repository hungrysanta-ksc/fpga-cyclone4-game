from nes_report083_prepare import sha,ROOT
FW='60d5ffcf283bdd1a69a62d8baac3f4f1dfad06c2562888c55e0491968663d91b'
RESTORE='1c3b40a3459d24114cb4d91ee9d861d1a08025a670ef25317ef489092203693b'
OFFLINE='b1f089f563727faca3b2327e0fd3c85f4d70126c3eeced18f6761bb54ff17708'
def digest(b):return hashlib.sha256(b).hexdigest()
def make_zip(path,files):
 with zipfile.ZipFile(path,'x',zipfile.ZIP_DEFLATED) as z:
  for n,b in sorted(files.items()):
   assert not n.startswith('/') and '..' not in Path(n).parts
   item=zipfile.ZipInfo(n,(2026,10,8,0,0,0));item.compress_type=zipfile.ZIP_DEFLATED;z.writestr(item,b)
 with zipfile.ZipFile(path) as z:
  assert set(z.namelist())==set(files) and z.testzip() is None
  for n,b in files.items():assert z.read(n)==b,n
 return {'bytes':path.stat().st_size,'sha256':sha(path),'members':{n:digest(b) for n,b in files.items()}}
