"""Instrumented 65816 WRAM routine for actual-read CRC and sparse VRAM DMA."""
import binascii
import struct
from build_nes_trace_replay import Asm, Code

# Supply read-only test inputs in WRAM. PPU writes execute on the CPU.
MASK, DETAILS, SIZES = 0x1000, 0x1080, 0x1070
STOP, STATUS = 0x1050, 0x1052
DATA = 0x2000

def image():
    c = Code(0x7e3000)
    emit = c.emit
    def imm(v): c.absolute(0xa9, v)
    def ld(a): c.absolute(0xad, a)
    def st(a): c.absolute(0x8d, a)
    def eq(a): c.absolute(0xcd, a)
    def branch_far(op, label):
        emit(op ^ 0x20, 3)
        c.jump(label)
    def call(label):
        c.jumps.append((len(c.data)+1, label))
        c.absolute(0x20, 0)
    def abort_if(op): branch_far(op, 'fail')
    def stop():
        ld(STOP)
        abort_if(0xd0)
    def word_at_x(addr): c.long(0xbf, 0x7f0000+addr)
    def byte_at_x(addr):
        word_at_x(addr)
        c.absolute(0x29, 255)
    # DP $00 CRC, $02 temporary, $04 end, $06 expected, $08 descriptor offset.
    c.label('gate')
    emit(0xc2,0x20)
    ld(0x1054)
    c.branch(0xf0,'gate')
    c.label('start')
    emit(0xc2,0x30)
    stop()
    ld(SIZES)
    c.absolute(0xc9,225)
    abort_if(0xb0)
    ld(SIZES+2)
    c.absolute(0xc9,DATA)
    abort_if(0x90)
    c.absolute(0xc9,DATA+4225)
    abort_if(0xb0)
    c.absolute(0x9c,8)
    c.absolute(0x9c,4)  # previous absolute end; reject overlapping declarations
    c.label('range')
    ld(8)
    eq(SIZES)
    branch_far(0xf0,'map_crc')
    abort_if(0xb0)
    emit(0xaa)
    c.absolute(0xbd,DETAILS)
    c.absolute(0x29,255)
    emit(0x38)
    c.absolute(0xe9,3)
    c.absolute(0xc9,3)
    abort_if(0xb0)
    emit(0x0a,0xa8)
    c.absolute(0xbd,DETAILS+1)
    emit(0x18)
    c.absolute(0x79,0xb200)
    abort_if(0xb0)
    eq(4)
    abort_if(0x90)
    st(10)
    c.absolute(0xbd,DETAILS+3)
    abort_if(0xf0)
    emit(0x18)
    c.absolute(0x6d,10)
    abort_if(0xb0)
    c.absolute(0xd9,0xb202)
    c.branch(0xf0,'in_bounds')
    abort_if(0xb0)
    c.label('in_bounds')
    st(4)
    c.absolute(0xbd,DETAILS+5)
    st(6)
    c.absolute(0xae,10)
    call('crc')
    ld(8)
    emit(0x18,0x69,7,0)
    st(8)
    c.jump('range')
    c.label('map_crc')
    stop()
    ld(SIZES+2)
    st(4)
    ld(SIZES+4)
    st(6)
    c.absolute(0xa2,DATA)
    call('crc')
    c.label('map')
    # Each expected row mask is checked before issuing its DMA runs.
    # Probe input contains one contiguous record stream (no mailbox stalls).
    c.absolute(0xa2,DATA)
    c.absolute(0x9c,12)  # row
    c.label('row')
    stop()
    c.absolute(0xac,12)
    c.absolute(0xb9,MASK)
    c.absolute(0x29,255)
    branch_far(0xf0,'next_row')
    st(14)
    emit(0x8a,0x18,0x69,2,0)
    eq(4)
    c.branch(0xf0,'header_ok')
    abort_if(0xb0)
    c.label('header_ok')
    byte_at_x(0)
    eq(12)
    abort_if(0xd0)
    emit(0xe8)
    byte_at_x(0)
    eq(14)
    abort_if(0xd0)
    emit(0xe8)
    ld(12)
    for _ in range(5): emit(0x0a)
    st(16)  # destination word
    c.label('group')
    ld(14)
    emit(0x4a)
    st(14)
    c.branch(0xb0,'run')
    ld(16)
    emit(0x18,0x69,4,0)
    st(16)
    c.jump('group')
    c.label('run')
    imm(8)
    st(18)
    c.label('extend')
    ld(14)
    emit(0x4a)
    c.branch(0x90,'dma')
    st(14)
    ld(18)
    emit(0x18,0x69,8,0)
    st(18)
    c.jump('extend')
    c.label('dma')
    emit(0x8a,0x18)
    c.absolute(0x6d,18)
    eq(4)
    c.branch(0xf0,'size_ok')
    abort_if(0xb0)
    c.label('size_ok')
    # Actual VBlank admission; start sufficiently early (lines 225..245).
    c.label('wait')
    stop()
    emit(0xe2,0x20)
    ld(0x2137)
    ld(0x213d)
    st(20)
    ld(0x213d)
    emit(0x29,1,0xc2,0x20)
    c.branch(0xd0,'wait')
    ld(20)
    c.absolute(0x29,255)
    c.absolute(0xc9,225)
    c.branch(0x90,'wait')
    c.absolute(0xc9,246)
    c.branch(0xb0,'wait')
    ld(16)
    st(0x2116)
    c.absolute(0x8e,0x4302)
    ld(18)
    st(0x4305)
    emit(0xe2,0x20)
    c.store(0x420b,1)
    emit(0xc2,0x20,0x8a,0x18)
    c.absolute(0x6d,18)
    emit(0xaa)
    ld(18)
    emit(0x4a,0x18)
    c.absolute(0x6d,16)
    st(16)
    ld(14)
    branch_far(0xd0,'group')
    c.label('next_row')
    c.absolute(0xee,12)
    ld(12)
    c.absolute(0xc9,64)
    branch_far(0x90,'row')
    c.absolute(0xec,4)
    abort_if(0xd0)
    stop()
    imm(1)
    st(STATUS)
    c.jump('done')
    c.label('fail')
    imm(2)
    st(STATUS)
    c.label('done')
    c.jump('done')
    c.label('crc')
    imm(65535)
    st(0)
    c.label('crc_check')
    emit(0xe4,4)  # CPX dp
    c.branch(0xf0,'crc_done')
    emit(0x8a,0x29,63,0)
    c.branch(0xd0,'byte')
    stop()
    c.label('byte')
    emit(0xa5,0,0xeb,0x85,2)  # high CRC byte in low accumulator
    c.long(0x5f,0x7f0000)
    emit(0x29,255,0,0x0a,0xa8,0xa5,2,0x29,0,255)
    c.absolute(0x59,0xb000)
    emit(0x85,0,0xe8)
    c.jump('crc_check')
    c.label('crc_done')
    ld(0)
    eq(6)
    abort_if(0xd0)
    emit(0x60)
    code = c.finish()
    boot = Asm(0x8000)
    boot.emit(0x78,0x18,0xfb,0xc2,0x30,0xa2,255,31,0x9a)
    boot.absolute(0xa9,len(code)-1)
    boot.absolute(0xa2,0x8100)
    boot.absolute(0xa0,0x3000)
    boot.emit(0x54,0x7e,0,0xe2,0x20,0xa9,0,0x48,0xab)
    for reg,val in [(0x4200,0),(0x2100,15),(0x2115,128),(0x4300,1),(0x4301,24),(0x4304,127)]:
        boot.store(reg,val)
    boot.store(0x1054,0)
    boot.store(0x1055,0)
    boot.long(0x5c,c.base)
    rom = bytearray([255])*32768
    rom[:len(boot.data)] = boot.finish()
    rom[256:256+len(code)] = code
    for i in range(256):
        struct.pack_into('<H',rom,0x3000+2*i,binascii.crc_hqx(bytes([i]),0))
    struct.pack_into('<4H',rom,0x3200,0,512,1056,4474)
    rom[0x7fc0:0x7fd5]=b'OUTPUT599 CHECK'.ljust(21,b' ')
    rom[0x7fd5:0x7fe0]=bytes([32,0,5,0,1,0,0,255,255,0,0])
    for i in range(0x7fe0,0x8000,2): struct.pack_into('<H',rom,i,0x8000)
    checksum=sum(rom)&65535
    struct.pack_into('<HH',rom,0x7fdc,checksum^65535,checksum)
    return rom, c.labels, len(code)
