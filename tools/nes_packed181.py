"""Version1813 paired exporter/receiver. No deployment or implicit old decode.

Reuse held_data for a run/byte group/raw group, with one9-bit count. On a run
break re-query the immutable lease after sending; no second64-bit lookahead.
END counters remain logical records/bytes, not compressed wire records.
"""
from pathlib import Path
import argparse, hashlib, json

ROOT = Path(__file__).resolve().parents[1]


def replace_once(s, old, new):
    assert s.count(old) == 1, (old, s.count(old))
    return s.replace(old, new)


def exporter(s):
    s = s.replace('16\'h1811', '16\'h1813')
    s = replace_once(s, 'reg [3:0] fill_detail;reg [2:0] patches;',
        '''reg [3:0] fill_detail;reg [2:0] patches;
 reg [8:0] pack_count;
 wire [12:0] pack_start=query_index-{4'd0,pack_count};
 wire [7:0] count_minus_one=pack_count[7:0]-8'd1;''')
    s = replace_once(s, 'VALUE:begin tx_valid=1;tx_data={(query_kind==7?3\'d6:query_kind),generation,query_index,held_data};end',
        '''VALUE:begin
    tx_valid=1;
    if(query_kind==7)tx_data={3'd7,generation,(13'h1000|pack_start),pack_count[3:0],held_data[59:0]};
    else if(query_kind==1||query_kind==5)
     tx_data={3'd7,generation,2'b11,query_kind,count_minus_one,held_data};
    else if(pack_count!=1)
     tx_data={3'd7,generation,2'b01,query_kind,count_minus_one,held_data};
    else tx_data={query_kind,generation,pack_start,held_data};
   end''')
    s = replace_once(s, 'fill_detail<=0;patches<=0;end', 'fill_detail<=0;patches<=0;pack_count<=0;end')
    s = replace_once(s, 'cycles<=0;records<=0;bytes_count<=0;', 'cycles<=0;records<=0;bytes_count<=0;pack_count<=0;')
    s = replace_once(s, 'ASK:if(query_index>=limit)begin',
        'ASK:if(query_index>=limit && pack_count!=0)state<=VALUE;\n    else if(query_index>=limit)begin')
    s = replace_once(s,
        'REPLY:if(response)begin if(!hit || (query_kind==7 && data[63:6]!=0))fail(3);else begin held_data<=data;state<=VALUE;end end\n    VALUE:if(tx_ready)begin records<=records+1\'b1;if(query_kind==7)bytes_count<=bytes_count+1\'b1;query_index<=query_index+1\'b1;state<=ASK;end',
        '''REPLY:if(response)begin
     if(!hit || (query_kind==7 && data[63:6]!=0))fail(3);
     else if(query_kind==7)begin
      held_data<={4'd0,held_data[53:0],data[5:0]};
      pack_count<=pack_count+1'b1;query_index<=query_index+1'b1;
      state<=pack_count==9?VALUE:ASK;
     end else if(query_kind==1||query_kind==5)begin
      if(data[63:8]!=0 || (query_kind==5 && data[7:6]!=0))fail(3);
      else begin held_data<={held_data[55:0],data[7:0]};
       pack_count<=pack_count+1'b1;query_index<=query_index+1'b1;
       state<=pack_count==7?VALUE:ASK;end
     end else if(pack_count==0)begin
      held_data<=data;pack_count<=1;query_index<=query_index+1'b1;state<=ASK;
     end else if(data==held_data && pack_count<256)begin
      pack_count<=pack_count+1'b1;query_index<=query_index+1'b1;state<=ASK;
     end else state<=VALUE; // re-query this immutable index after flushing run
    end
    VALUE:if(tx_ready)begin
     records<=records+{7'd0,pack_count};
     if(query_kind==7)bytes_count<=bytes_count+{7'd0,pack_count};
     pack_count<=0;held_data<=0;state<=ASK;
    end''')
    s = replace_once(s, 'query_kind<=7;query_index<=0;state<=ASK;',
                     'query_kind<=7;query_index<=0;pack_count<=0;held_data<=0;state<=ASK;')
    return '//1813 Packed candidate generated by nes_packed181.py; not1811 wire compatible.\n'+s


def receiver(s):
    s = s.replace('0x1811', '0x1813')
    s = replace_once(s, 'static bool record(', 'static bool logical_record(')
    pos = s.index('bool nes_native165_packet(')
    wrapper = '''/*1813 Compressed records expand through the original checked logical
 * decoder. No extra frame buffer; every count/phase/base is validated first.
 * A failure poisons the tentative frame; only COMMIT can expose pixels. */
static bool record(struct nes_native165 *s,unsigned kind,unsigned gen,unsigned index,uint64_t v){
 if(kind!=7 || index<0x800){
  if(kind==1||kind==5||(kind==6&&s->next_kind==7))return fail(s,33);
  return logical_record(s,kind,gen,index,v);
 }
 if(s->state!=NES_NATIVE165_RECEIVING||gen!=s->generation)return fail(s,33);
 if(index>=0x1000 && index<0x1700){
  unsigned start=index-0x1000,n=(unsigned)(v>>60),left=(unsigned)s->patch_count*256-s->last_tile;
  uint64_t colors=v&UINT64_C(0x0fffffffffffffff);
  if(s->next_kind!=7||start!=s->last_tile||!n||n>10||n!=(left>10?10:left)||
     (colors>>(6*n)))return fail(s,33);
  for(unsigned i=0;i<n;i++)if(!logical_record(s,6,gen,start+i,(colors>>(6*(n-1-i)))&63))return false;
  return true;
 }
 unsigned k=(index>>8)&7,n=(index&255)+1;
 if(k>=6||s->next_kind==7||n>(unsigned)s->counts[k]-s->at[k])return fail(s,33);
 unsigned start=s->at[k];
 if((index&0x1800)==0x800){
  if(k==1||k==5||n<2)return fail(s,33);
  for(unsigned i=0;i<n;i++)if(!logical_record(s,k,gen,start+i,v))return false;
 }else if((index&0x1800)==0x1800){
  unsigned left=s->counts[k]-s->at[k];
  if((k!=1&&k!=5)||n>8||n!=(left>8?8:left)||(n<8 && v>>(8*n)))return fail(s,33);
  for(unsigned i=0;i<n;i++)if(!logical_record(s,k,gen,start+i,(v>>(8*(n-1-i)))&255))return false;
 }else return fail(s,33);
 return true;
}
'''
    return s[:pos]+wrapper+s[pos:]


def spi(s):
    # Extended kind7 is DATA. Only low control indices terminate a block.
    return replace_once(s, '(held[95:93]==7&&held[76:64]!=0)',
                        "(held[95:93]==7&&held[76:64]!=0&&held[76:64]<13'h800)")


def prepare(out, spi_source):
    out.mkdir(parents=True, exist_ok=False)
    pins = json.loads((ROOT/'analysis/wire181-verification.json').read_bytes())['public_sources']
    sources = {}
    for name, dest, fn in [('src/nes/video/nes_native_export181.sv','nes_native_export181.sv',exporter),
                           ('src/nes/firmware/nes_native181.c','nes_native165.c',receiver),
                           ('src/nes/firmware/nes_native181.h','nes_native165.h',lambda s:s)]:
        p=ROOT/name; h=hashlib.sha256(p.read_bytes()).hexdigest();assert h==pins[name]
        sources[name]=h
        (out/dest).write_text(fn(p.read_text()),encoding='utf8',newline='\n')
    expected=json.loads((ROOT/'analysis/wire181-verification.json').read_bytes())['wire']['sources']['baseline/nes_native_spi165.sv']
    assert hashlib.sha256(spi_source.read_bytes()).hexdigest()==expected
    sources['baseline/nes_native_spi165.sv']=expected
    (out/'nes_native_spi165.sv').write_text(spi(spi_source.read_text()),encoding='utf8',newline='\n')
    result=dict(version='1813',sources=sources,generated={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in out.iterdir()},
                generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                fit=False,production_installed=False)
    (out/'preparation.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf8')
    return result


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--out',type=Path,required=True);p.add_argument('--spi-source',type=Path,required=True)
    a=p.parse_args();print(json.dumps(prepare(a.out,a.spi_source),indent=2))
