"""Production-entry relocation and fused input routines for full encoder246."""
from nes_operand245 import assemble as previous, LAYOUT, OPS as OLDOPS

OPS={**OLDOPS,'SETARG':30}

def assemble():
    original,old_entries=previous()
    # Drop test-only and no-longer-called routines, then relocate every branch.
    # Shared internal literal/flush labels remain intact.
    ranges=[(23,52),(60,65),(83,95),(264,273),(280,301),(322,327)]
    keep=[pc for pc in range(len(original)) if not any(lo<=pc<hi for lo,hi in ranges)]
    mapping={old:new for new,old in enumerate(keep)}
    words=[]
    for pc in keep:
        w=original[pc];op=w>>13
        if op in (OPS['JMP'],OPS['JZ'],OPS['JC']):w=(op<<13)|mapping[w&511]
        words.append(w)
    entries={n:mapping[pc] for n,pc in old_entries.items() if pc in mapping}
    # Cold/raw caller needs the new length, avoiding a host RF read per byte.
    words[mapping[old_entries['raw_append']+8]]=(OPS['LD']<<13)|(LAYOUT['lit_len'][0]-96)
    def emit(op,v=0):words.append((OPS[op]<<13)|v)
    def rf(op,n,i=0):emit(op,LAYOUT[n][i]-96)
    entries['direct_literal']=len(words)
    # arg0={new,old},arg1=absolute byte offset. Neither byte can be consumed
    # twice when literal returns flush/retry; the outer controller pins both.
    emit('ARG',0);rf('ST','old_byte');emit('ARG',2);rf('ST','byte_at')
    emit('ARG',3);emit('ANDI',31);rf('ST','byte_at',1)
    emit('ARG',1);emit('SETARG',0);emit('LDI',0);emit('SETARG',1);emit('JMP',entries['literal'])
    entries['row_literal']=len(words)
    # arg0=index,arg1.low=raster flag. Load O/N here; no host byte mirrors.
    emit('ARG',0);rf('ADD','row_start');rf('ST','byte_at')
    rf('LD','row_start',1);emit('ADCI',0);emit('ANDI',31);rf('ST','byte_at',1)
    emit('ARG',0);emit('ADDR',0);emit('LDP');rf('ST','old_byte')
    emit('ARG',0);emit('ADDI',128);emit('ADDR',0);emit('LDP');emit('SETARG',0);emit('JMP',entries['literal'])
    entries['raw_begin']=len(words)
    emit('LDI',0)
    for n in ('lit_at','lit_len','lit_used','gap'):
        for i in range(len(LAYOUT[n])):rf('ST',n,i)
    emit('HALT')
    assert len(words)<=512,len(words)
    return words,entries

def header():
    words,entries=assemble()
    return '// Generated by nes_operand246.py; do not hand-edit.\n'+''.join(
        f'localparam [8:0] OP_{name.upper()}=9\'d{pc};\n' for name,pc in entries.items())

